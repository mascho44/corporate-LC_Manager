const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context=vm.createContext({document:{addEventListener(){}}});
vm.runInContext(fs.readFileSync('src/main/resources/static/text-diff.js','utf8'),context);
context.esc=context.diffEscape;
assert.equal(context.textDiff('unchanged','unchanged').before,'unchanged');
assert.match(context.textDiff('EUR 1000','EUR 1200').before,/<del>1000<\/del>/);
assert.match(context.textDiff('EUR 1000','EUR 1200').after,/<ins>1200<\/ins>/);
assert.equal(context.textDiff('','new').after,'<ins>new</ins>');
assert.equal(context.textDiff('old','').before,'<del>old</del>');
assert.ok(!context.textDiff('<script>','<img>').after.includes('<img>'));
const large='word '.repeat(2000);
assert.ok(context.textDiff(large+'old',large+'new').after.includes('<ins>new</ins>'));
vm.runInContext(fs.readFileSync('src/main/resources/static/app.js','utf8').split('function renderInboxSuggestions')[0],context);
const amendment={beforeState:JSON.stringify({amount:'1000',rawMessage:'MT700 <unsafe>'}),afterState:JSON.stringify({amount:'1200',rawMessage:'MT700 <unsafe>'}),rawMessage:'MT707 <unsafe>'};
const html=context.amendmentDiffHtml(amendment);
assert.match(html,/<ins>1200<\/ins>/);
assert.ok(html.includes('MT707 &lt;unsafe&gt;'));
assert.match(context.amendmentDiffHtml({}),/Altbestand/);
assert.match(context.amendmentDiffHtml({beforeState:'broken',afterState:'{}'}),/konnte nicht/);
vm.runInContext(fs.readFileSync('src/main/resources/static/document-comparison.js','utf8'),context);
assert.match(context.comparisonHtml({resultJson:JSON.stringify({beforeName:'v1',afterName:'v2',fields:[{name:'Betrag',before:'1000',after:'1200',changed:true}]}),beforeDocumentId:'a',afterDocumentId:'b'}),/<ins>1200<\/ins>/);
console.log('Text diff and both comparison renderers: all checks passed');
